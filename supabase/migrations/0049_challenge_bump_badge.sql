-- 0049 만삭·D라인: 임산부 배지를 같은 사진에 함께 찍어야 참가 인정 (2026-10-30 사장님 요청)
--
-- 배지는 보건소가 임신 확인 뒤 주므로, 배 + 배지가 한 사진에 있으면 남의 사진·인터넷 사진을 걸러낼 수 있다.
-- 배지에는 이름·병원명이 없어 개인정보 부담도 없다. 기준을 흐리는 예외 문구는 넣지 않는다.
begin;
update public.challenges set
  description = '지금만 남길 수 있는 D라인! 배가 나온 모습과 임산부 배지를 한 사진에 담아 참여해요.',
  guide = array[
    '배가 나온 옆모습과 임산부 배지가 한 사진에 함께 보여야 해요',
    '배지는 옷이나 가방에 단 채로, 또는 손에 들고 찍어 주세요',
    '태명이나 주수를 한 줄로 남겨 주세요',
    '직접 찍은 사진만 인정돼요. 1위는 원본 사진을 확인한 뒤 확정해요'
  ]
where id = 'bump';

-- 경품: 대회마다 매달 1위 1명에게 배민·올리브영 상품권 2만 원, 볼살(광고를 모으는 대회)만 4만 원.
-- 한 사람 5만 원 이하라 원천징수·주민번호 수집이 필요 없다.
update public.challenges set prize = '매달 점수(응원+투표)가 가장 높은 1명에게 배민 또는 올리브영 상품권 2만 원을 드려요.'
 where id <> 'cheeks';
update public.challenges set prize = '매달 점수(응원+투표)가 가장 높은 1명에게 배민 또는 올리브영 상품권 4만 원을 드려요.'
 where id = 'cheeks';
commit;
